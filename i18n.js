  function resolveLang(pref) {
    if (pref && pref !== 'auto' && DICT[pref]) return pref;
    let ui = '';
    try { ui = (g.chrome && g.chrome.i18n && g.chrome.i18n.getUILanguage()) || ''; } catch (e) { /* 무시 */ }
    if (!ui && g.navigator) ui = g.navigator.language || '';
    ui = ui.toLowerCase();
    if (ui.startsWith('ko')) return 'ko';
    if (ui.startsWith('ja')) return 'ja';
    return 'en';
  }

  // 메시지: 문자열 키 또는 { key, vars } 또는 이미 번역된 일반 문자열
  function t(lang, key, vars) {
    if (key && typeof key === 'object') return t(lang, key.key, key.vars);
    const table = DICT[lang] || DICT.en;
    let s = table[key];
    if (s == null) s = DICT.ko[key];
    if (s == null) return String(key == null ? '' : key);
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => {
        const v = vars[k];
        if (v == null) return m;
        if (typeof v === 'object' && v.key) return t(lang, v.key, v.vars);
        if (typeof v === 'string' && DICT.ko[v] != null) return t(lang, v);
        return String(v);
      });
    }
    return s;
  }

  // 오류 객체 → 번역 가능한 값
  function errVal(e) {
    if (e && e.i18nKey) return { key: e.i18nKey };
    return String((e && e.message) || e);
  }

  function err(key) {
    const e = new Error(key);
    e.i18nKey = key;
    return e;
  }

  g.CLTR_I18N = { DICT, resolveLang, t, errVal, err };
